// Checks register-insensitive environment variable to verify SSL
export function shouldVerifySsl(): boolean {
  const val = process.env.GIGACHAT_VERIFY_SSL;
  if (val === undefined) return true;
  const normalized = val.trim().toLowerCase();
  return normalized !== "false" && normalized !== "0" && normalized !== "off" && normalized !== "no";
}

// Thread-safe HTTPS Agents pool cache
let cachedVerifyAgent: https.Agent | null = null;
let cachedNoVerifyAgent: https.Agent | null = null;
let cachedCaContents: Buffer | string | null = null;
let cachedCaPath: string | null = null;

function splitPemCerts(pem: string | Buffer): string[] {
  const pemStr = typeof pem === "string" ? pem : pem.toString("utf8");
  const certs: string[] = [];
  const regex = /-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----/g;
  let match;
  while ((match = regex.exec(pemStr)) !== null) {
    certs.push(match[0]);
  }
  return certs;
}

export function getHttpsAgent(verifySsl: boolean, caBundlePath: string): https.Agent {
  if (!verifySsl) {
    if (!cachedNoVerifyAgent) {
      cachedNoVerifyAgent = new https.Agent({
        rejectUnauthorized: false,
        keepAlive: true,
        maxSockets: 100,
        maxFreeSockets: 10
      });
    }
    return cachedNoVerifyAgent;
  }

  if (!cachedVerifyAgent || cachedCaPath !== caBundlePath) {
    const agentOptions: https.AgentOptions = {
      keepAlive: true,
      maxSockets: 100,
      maxFreeSockets: 10
    };

    const extraCAs: string[] = [];
    try {
      if (caBundlePath && fs.existsSync(caBundlePath) && fs.statSync(caBundlePath).isFile()) {
        if (!cachedCaContents || cachedCaPath !== caBundlePath) {
          cachedCaContents = fs.readFileSync(caBundlePath);
        }
        extraCAs.push(...splitPemCerts(cachedCaContents));
      } else {
        extraCAs.push(...splitPemCerts(BUILTIN_CA_BUNDLE));
      }
    } catch (err) {
      logger.warn("Failed to load external CA file, falling back to built-in CA", err);
      extraCAs.push(...splitPemCerts(BUILTIN_CA_BUNDLE));
    }

    agentOptions.ca = [...tls.rootCertificates, ...extraCAs];
    cachedVerifyAgent = new https.Agent(agentOptions);
    cachedCaPath = caBundlePath;
  }

  return cachedVerifyAgent;
}
